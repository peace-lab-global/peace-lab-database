HEADER = "## 跨板块关联"


def main():
    added = 0
    for topic, links in BRIDGES.items():
        idx = os.path.join(ROOT, "06-临床专题", topic, "INDEX.md")
        if not os.path.isfile(idx):
            print(f"跳过(无INDEX): {topic}")
            continue
        with open(idx, encoding="utf-8") as f:
            text = f.read()
        if HEADER in text:
            print(f"已存在,跳过: {topic}")
            continue
        rows = []
        srcdir = os.path.dirname(idx)
        for label, target, note in links:
            tp = os.path.join(ROOT, target)
            if not os.path.isfile(tp):
                print(f"  [{topic}] 目标缺失,略过: {target}")
                continue
            rel = quote(os.path.relpath(tp, srcdir), safe="/-_.~")
            rows.append(f"| [{label}]({rel}) | {note} |")
        if not rows:
            continue
        section = (
            f"\n{HEADER}\n\n"
            "> 本专题为跨支柱聚合层, 以下为其他板块中与本病种直接相关的知识入口。\n\n"
            "| 关联入口 | 说明 |\n|---|---|\n" + "\n".join(rows) + "\n"
        )
        if EXECUTE:
            with open(idx, "a", encoding="utf-8") as f:
                f.write(section)
        added += 1
        print(f"追加: {topic} ({len(rows)} 条)")
    print(f"共处理 {added} 个专题, execute={EXECUTE}")


if __name__ == "__main__":
    main()
